//! The `vt` subcommands. Each returns an [`Outcome`]: what to print and the exit status.

use std::path::{Path, PathBuf};
use std::process::{Command, Stdio};

use oxrdf::Graph;
use vertep_core::ir::Chart;
use vertep_core::types::{BasicTyper, ChartTypes, Diagnostic, check_chart};
use vertep_rdf::io::write_graph;
use vertep_rdf::iri::percent_encode_into;
use vertep_rdf::types::{ChartSchemas, TypeIris, TypeShapes};
use vertep_rdf::{RdfFormat, chart_version, project};

use crate::cel;
use crate::surface::{self, Checks, Loaded, Surface, located};

/// What a command prints and its exit status.
#[derive(Clone, Debug, Default, PartialEq, Eq)]
pub struct Outcome {
    /// Standard output.
    pub stdout: String,
    /// Standard error.
    pub stderr: String,
    /// Exit status: 0 on success, 1 when the chart fails the command, 2 on usage or I/O
    /// errors.
    pub code: i32,
}

impl Outcome {
    fn ok(stdout: String) -> Self {
        Outcome {
            stdout,
            ..Outcome::default()
        }
    }

    fn fail(code: i32, lines: impl IntoIterator<Item = String>) -> Self {
        let mut stderr = String::new();
        for l in lines {
            stderr.push_str(&l);
            stderr.push('\n');
        }
        Outcome {
            stdout: String::new(),
            stderr,
            code,
        }
    }
}

/// The projections `vt schema` prints.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum SchemaFormat {
    /// Rust types (generated by `vertep-macros`).
    Rust,
    /// JSON Schema 2020-12 documents.
    JsonSchema,
    /// SHACL Core shapes in Turtle.
    Shacl,
    /// The CEL type environment.
    Cel,
}

fn read_file(path: &Path) -> Result<String, Outcome> {
    std::fs::read_to_string(path)
        .map_err(|e| Outcome::fail(2, [format!("{}: cannot read: {e}", path.display())]))
}

fn load(path: &Path, checks: Checks) -> Result<Loaded, Outcome> {
    let content = read_file(path)?;
    let file = path.display().to_string();
    surface::load(&file, &content, checks).map_err(|errs| Outcome::fail(1, errs))
}

fn diag(file: &str, d: &Diagnostic) -> String {
    located(
        file,
        d.span.line,
        d.span.column,
        &format!("{}: {}", d.location, d.message),
    )
}

/// Type-check a loaded chart: the core checker with the datamodel's basic typer, then, for
/// CEL charts, the CEL datamodel's static checking against the projected type environment.
fn typecheck_chart(file: &str, chart: &Chart) -> Result<ChartTypes, Vec<String>> {
    let typer = BasicTyper::for_datamodel(&chart.datamodel);
    let types = check_chart(chart, &typer)
        .map_err(|ds| ds.iter().map(|d| diag(file, d)).collect::<Vec<_>>())?;
    if chart.datamodel == vertep_dm_cel::CEL {
        let options = vertep_dm_cel::LoadOptions {
            env: cel::type_env(&types),
            ..vertep_dm_cel::LoadOptions::default()
        };
        if let Err(errs) = vertep_dm_cel::load(chart, &options) {
            return Err(errs.0.iter().map(|e| format!("{file}: {e}")).collect());
        }
    }
    Ok(types)
}

/// `vt typecheck <chart>`: report every type error with its location.
// @tg: implements:: [[openspec:type-system#Command Line Type Tools]]
pub fn typecheck(path: &Path) -> Outcome {
    let loaded = match load(path, Checks::Types) {
        Ok(l) => l,
        Err(o) => return o,
    };
    let file = path.display().to_string();
    match typecheck_chart(&file, &loaded.chart) {
        Ok(t) if t.typed => Outcome::ok(format!(
            "{file}: ok: {} named types, {} typed events, {} context fields\n",
            t.declarations.types.len(),
            t.events.iter().count(),
            t.context.len()
        )),
        Ok(_) => Outcome::ok(format!("{file}: ok: untyped\n")),
        Err(errs) => {
            let n = errs.len();
            let mut o = Outcome::fail(1, errs);
            o.stderr.push_str(&format!(
                "{file}: {n} type error{}\n",
                if n == 1 { "" } else { "s" }
            ));
            o
        }
    }
}

/// `vt schema <chart> --format ...`: print a projection of the chart's types.
// @tg: implements:: [[openspec:type-system#Command Line Type Tools]] {confidence: partial, note: "--format rust defers to the vertep-macros code generator"}
pub fn schema(path: &Path, format: SchemaFormat) -> Outcome {
    let loaded = match load(path, Checks::Types) {
        Ok(l) => l,
        Err(o) => return o,
    };
    let file = path.display().to_string();
    let types = match typecheck_chart(&file, &loaded.chart) {
        Ok(t) => t,
        Err(errs) => return Outcome::fail(1, errs),
    };
    match format {
        SchemaFormat::JsonSchema => match ChartSchemas::of(&types) {
            Ok(s) => match serde_json::to_string_pretty(&s.to_json()) {
                Ok(text) => Outcome::ok(text + "\n"),
                Err(e) => Outcome::fail(2, [format!("{file}: {e}")]),
            },
            Err(names) => Outcome::fail(
                1,
                [format!("{file}: undeclared types: {}", names.join(", "))],
            ),
        },
        SchemaFormat::Shacl => Outcome::ok(shacl(&loaded.chart, &types)),
        SchemaFormat::Cel => Outcome::ok(cel::describe(&types)),
        SchemaFormat::Rust => Outcome::fail(
            2,
            [format!(
                "{file}: the Rust projection is generated at compile time by the statechart! and \
                 include_chart! macros (vertep-macros); use include_chart!(\"{file}\") to get the \
                 typed Rust API"
            )],
        ),
    }
}

/// The SHACL projection of a chart's types in Turtle: the definition and node shape of every
/// named type at its type IRI, the context shape at `<version>#context` and each typed event's
/// payload shape at `<version>#event.<name>`.
fn shacl(chart: &Chart, types: &ChartTypes) -> String {
    let version = chart_version(chart);
    let decls = &types.declarations;
    let iris = TypeIris::of(decls);
    let mut g = Graph::new();
    g.extend(iris.definitions(decls).iter());
    let mut shapes = TypeShapes::new(decls, &iris);
    shapes.named_types();
    if types.typed {
        shapes.shape_at(version.as_str(), "context", &types.context_type());
        for (name, payload) in types.events.iter() {
            if let Some(p) = payload {
                let mut frag = String::from("event.");
                percent_encode_into(name, &mut frag);
                shapes.shape_at(version.as_str(), &frag, p);
            }
        }
    }
    g.extend(shapes.into_graph().iter());
    let base = format!("{version}#");
    let prefixes = [
        ("sh", "http://www.w3.org/ns/shacl#"),
        ("vt", vertep_rdf::vocab::VT),
        ("xsd", "http://www.w3.org/2001/XMLSchema#"),
        ("rdf", "http://www.w3.org/1999/02/22-rdf-syntax-ns#"),
        ("c", base.as_str()),
    ];
    write_graph(&g, RdfFormat::Turtle, None, &prefixes)
}

/// `vt validate <chart>`: well-formedness and SHACL conformance of the chart's projection.
// @tg: implements:: [[openspec:type-system#Command Line Type Tools]]
pub fn validate(path: &Path) -> Outcome {
    let loaded = match load(path, Checks::Structure) {
        Ok(l) => l,
        Err(o) => return o,
    };
    let file = path.display().to_string();
    let mut problems = Vec::new();
    if let Err(vs) = vertep_core::validate::validate(&loaded.chart) {
        problems.extend(
            vs.iter()
                .map(|v| located(&file, v.span.line, v.span.column, &v.to_string())),
        );
    }
    let projected = project(&loaded.chart);
    let report = vertep_rdf::validate(&projected.graph);
    problems.extend(
        report
            .results
            .iter()
            .map(|r| format!("{file}: shapes: {r}")),
    );
    if let Err(e) = vertep_rdf::shacl::Shapes::from_graph(&projected.graph) {
        problems.push(format!("{file}: type shapes: {}", e.0));
    }
    if problems.is_empty() {
        Outcome::ok(format!("{file}: ok: {}\n", projected.version))
    } else {
        Outcome::fail(1, problems)
    }
}

/// `vt gen ts <chart> [--name N]`: print the TypeScript module for `@vertep/web`: the event
/// union, the context interface, the state-id union, the typed chart spec and a typed
/// `create<N>Actor`. An untyped chart gets dynamic JSON value types.
// @tg: implements:: [[openspec:wasm-bindings#Generated TypeScript Types]]
pub fn gen_ts(path: &Path, name: Option<&str>) -> Outcome {
    let loaded = match load(path, Checks::Types) {
        Ok(l) => l,
        Err(o) => return o,
    };
    let file = path.display().to_string();
    let types = match typecheck_chart(&file, &loaded.chart) {
        Ok(t) => t,
        Err(errs) => return Outcome::fail(1, errs),
    };
    let text = match read_file(path) {
        Ok(t) => t,
        Err(o) => return o,
    };
    let stem = path
        .file_stem()
        .map(|s| s.to_string_lossy().into_owned())
        .unwrap_or_default();
    let prefix = vertep_rdf::types::typescript::pascal(
        name.or(loaded.chart.name.as_deref())
            .unwrap_or(stem.split('.').next().unwrap_or("chart")),
    );
    let format = match loaded.surface {
        Surface::Scxml => "scxml",
        Surface::Yaml => "yaml",
        _ => "rdf",
    };
    let version = chart_version(&loaded.chart);
    let src = vertep_rdf::types::typescript::TsSource {
        name: &prefix,
        text: &text,
        format,
        version: version.as_str(),
    };
    Outcome::ok(vertep_rdf::types::typescript::ts_module(
        &loaded.chart,
        &types,
        &src,
    ))
}

/// `vt hash <chart>`: print the chart version IRI.
// @tg: implements:: [[openspec:type-system#Command Line Type Tools]]
pub fn hash(path: &Path) -> Outcome {
    match load(path, Checks::Structure) {
        Ok(l) => Outcome::ok(format!("{}\n", chart_version(&l.chart))),
        Err(o) => o,
    }
}

/// `vt convert <input> --to <surface>`: convert between surfaces, refusing to write anything
/// when the conversion would lose information.
// @tg: implements:: [[openspec:yaml-format#Command Line Conversion]]
pub fn convert(path: &Path, to: Surface, output: Option<&Path>) -> Outcome {
    let loaded = match load(path, Checks::Structure) {
        Ok(l) => l,
        Err(o) => return o,
    };
    let file = path.display().to_string();
    let mut lost = loaded.lost.clone();
    let written = match surface::write(&loaded.chart, to) {
        Ok(w) => Some(w),
        Err(problems) => {
            lost.extend(problems.into_iter().map(|p| format!("{file}: {p}")));
            None
        }
    };
    match written {
        Some(text) if lost.is_empty() => match output {
            None => Outcome::ok(text),
            Some(out) => match std::fs::write(out, text) {
                Ok(()) => Outcome::ok(String::new()),
                Err(e) => Outcome::fail(2, [format!("{}: cannot write: {e}", out.display())]),
            },
        },
        _ => {
            let mut lines = vec![format!(
                "{file}: refusing to convert {} to {to}: it would lose:",
                loaded.surface
            )];
            lines.extend(lost.into_iter().map(|l| format!("  - {l}")));
            Outcome::fail(1, lines)
        }
    }
}

/// The environment variable naming the Lean checker executable.
pub const CERTIFY_ENV: &str = "VT_CERTIFY";

/// The name of the Lean checker executable looked up on `PATH`.
pub const CERTIFY_BIN: &str = "vt-certify";

fn find_checker() -> Option<PathBuf> {
    if let Some(p) = std::env::var_os(CERTIFY_ENV) {
        let p = PathBuf::from(p);
        return p.is_file().then_some(p);
    }
    let path = std::env::var_os("PATH")?;
    std::env::split_paths(&path)
        .map(|d| d.join(CERTIFY_BIN))
        .find(|p| p.is_file())
}

/// `vt certify <chart>`: run the Lean-compiled checker on the chart's canonical N-Quads and
/// print the certificate it emits. The checker is found through `VT_CERTIFY` or as
/// `vt-certify` on `PATH` (built by `lake build` in `lean/vertep-lean`); it is run as
/// `vt-certify --chart <file.nq>` on the chart's published N-Quads and prints the certificate
/// as N-Triples. It exits 0 when it certifies, 1 when the chart is not well-formed and 2 when
/// the graph is not a chart projection.
// @tg: implements:: [[openspec:type-system#Command Line Type Tools]]
pub fn certify(path: &Path) -> Outcome {
    let loaded = match load(path, Checks::Structure) {
        Ok(l) => l,
        Err(o) => return o,
    };
    let Some(checker) = find_checker() else {
        return Outcome::fail(
            1,
            [
                format!("vt certify: the Lean checker `{CERTIFY_BIN}` is not installed."),
                "Build it from the Lean model and put it on PATH, or point VT_CERTIFY at it:".into(),
                "  cd lean/vertep-lean && lake build && export VT_CERTIFY=$PWD/.lake/build/bin/vt-certify".into(),
                "No certificate was produced.".into(),
            ],
        );
    };
    let projected = project(&loaded.chart);
    let nquads = vertep_rdf::write_chart(&projected, RdfFormat::NQuads);
    let file = std::env::temp_dir().join(format!(
        "vt-certify-{}-{}.nq",
        std::process::id(),
        projected
            .version
            .as_str()
            .rsplit(':')
            .next()
            .unwrap_or("chart")
    ));
    if let Err(e) = std::fs::write(&file, nquads.as_bytes()) {
        return Outcome::fail(2, [format!("{}: cannot write: {e}", file.display())]);
    }
    let child = Command::new(&checker)
        .arg("--chart")
        .arg(&file)
        .stdout(Stdio::piped())
        .stderr(Stdio::piped())
        .spawn();
    let child = match child {
        Ok(c) => c,
        Err(e) => {
            let _ = std::fs::remove_file(&file);
            return Outcome::fail(2, [format!("{}: cannot run: {e}", checker.display())]);
        }
    };
    let result = child.wait_with_output();
    let _ = std::fs::remove_file(&file);
    match result {
        Ok(out) => {
            let code = out.status.code().unwrap_or(1);
            Outcome {
                stdout: if code == 0 {
                    String::from_utf8_lossy(&out.stdout).into_owned()
                } else {
                    String::new()
                },
                stderr: String::from_utf8_lossy(&out.stderr).into_owned(),
                code,
            }
        }
        Err(e) => Outcome::fail(2, [format!("{}: {e}", checker.display())]),
    }
}

/// `vt cluster reshard <dir> <out>`: the offline doubling of a stopped cluster's shard count.
/// Reads the cluster metadata and shard files of `dir`, refuses while its `leases` file lists
/// a live lease (naming the nodes), writes twice as many shard files and the new metadata to
/// `out`, and verifies every actor's journal there. `dir` is left untouched.
// @tg: implements:: [[openspec:shard-placement#Resharding Procedure]]
pub fn cluster_reshard(dir: &Path, out: &Path) -> Outcome {
    match vertep_cluster::rebalance::reshard_directory(dir, out) {
        Ok((meta, report)) => Outcome::ok(format!(
            "resharded {} to {} shards: {} actors, {} entries copied to {}\n",
            report.old.get(),
            meta.shard_count.get(),
            report.actors.len(),
            report.entries,
            out.display()
        )),
        Err(e @ vertep_cluster::ReshardError::LeasesHeld(_)) => Outcome::fail(1, [e.to_string()]),
        Err(e) => Outcome::fail(2, [e.to_string()]),
    }
}
