#!/usr/bin/env python3
"""Render the stability-tier tables of README.md and site/docs/tiers.html from the manifests.

Every crate under crates/ declares its tier in `[package.metadata.vertep]`, each npm package in
the `vertep` key of its package.json and the Python package in `[tool.vertep]` of its
pyproject.toml: `tier` is `stable`, `preview` or `experimental`, and `tier-reason` (npm:
`tierReason`) says why, in one line. This script replaces the text between the
`<!-- tiers:begin -->` and `<!-- tiers:end -->` markers of both files, so the tables cannot
drift from the manifests. Run it from anywhere after a tier changes:

    python3 site/tools/tiers.py           # rewrite the tables
    python3 site/tools/tiers.py --check   # exit 1 if a tier is missing or a table is stale (CI)
    python3 site/tools/tiers.py --self-test  # prove both failures on a scratch copy (CI)

Needs Python 3.11 or later (tomllib).
"""

import json
import re
import sys
import tomllib
from html import escape
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
README = ROOT / "README.md"
PAGE = ROOT / "site" / "docs" / "tiers.html"
TIERS = ("stable", "preview", "experimental")
BEGIN, END = "<!-- tiers:begin -->", "<!-- tiers:end -->"


class Package:
    def __init__(self, name, kind, manifest, published, description, tier, reason, ships_as=None):
        self.name, self.kind, self.manifest = name, kind, manifest
        self.published, self.description = published, description
        self.tier, self.reason, self.ships_as = tier, reason, ships_as

    @property
    def url(self):
        if self.kind == "crate":
            return f"https://crates.io/crates/{self.name}"
        if self.kind == "npm":
            return f"https://www.npmjs.com/package/{self.name}"
        return f"https://pypi.org/project/{self.name}/"

    @property
    def registry(self):
        return {"crate": "crates.io", "npm": "npm", "python": "PyPI"}[self.kind]


def collect():
    """Every package with its tier, in workspace order, and the problems found."""
    packages, problems = [], []
    workspace = tomllib.loads((ROOT / "Cargo.toml").read_text())["workspace"]["members"]
    for member in workspace:
        if not member.startswith("crates/"):
            continue  # the examples package is not a product
        path = ROOT / member / "Cargo.toml"
        pkg = tomllib.loads(path.read_text())["package"]
        meta = pkg.get("metadata", {}).get("vertep", {})
        ships_as = None
        if pkg["name"] == "vertep-wasm":
            ships_as = "@vertep/web"
        elif pkg["name"] == "vertep-py":
            ships_as = "vertep on PyPI"
        packages.append(Package(
            pkg["name"], "crate", path.relative_to(ROOT), pkg.get("publish", True) is not False,
            pkg.get("description", ""), meta.get("tier"), meta.get("tier-reason"), ships_as))
    for path in sorted((ROOT / "bindings/js/packages").glob("*/package.json")):
        pkg = json.loads(path.read_text())
        meta = pkg.get("vertep", {})
        packages.append(Package(
            pkg["name"], "npm", path.relative_to(ROOT), not pkg.get("private", False),
            pkg.get("description", ""), meta.get("tier"), meta.get("tierReason")))
    path = ROOT / "bindings/python/pyproject.toml"
    py = tomllib.loads(path.read_text())
    meta = py.get("tool", {}).get("vertep", {})
    packages.append(Package(
        py["project"]["name"], "python", path.relative_to(ROOT), True,
        py["project"].get("description", ""), meta.get("tier"), meta.get("tier-reason")))

    for p in packages:
        if p.tier is None:
            problems.append(f"{p.manifest}: {p.name} declares no tier")
        elif p.tier not in TIERS:
            problems.append(f"{p.manifest}: {p.name} has tier {p.tier!r}, not one of {', '.join(TIERS)}")
        if not p.reason:
            problems.append(f"{p.manifest}: {p.name} gives no reason for its tier")
    return packages, problems


def by_tier(packages):
    order = {t: i for i, t in enumerate(TIERS)}
    # The facade first, then workspace order within a tier (sorted() is stable).
    return sorted(packages, key=lambda p: (order.get(p.tier, len(TIERS)), p.name != "vertep" or p.kind != "crate"))


def readme_table(packages):
    """Published packages only: the crates on crates.io, the npm packages and the wheel."""
    rows = ["| Package | Tier | What it is |", "| --- | --- | --- |"]
    for p in by_tier(packages):
        if not p.published:
            continue
        label = f"`{p.name}`" if p.kind != "python" else "`vertep` (Python)"
        desc = p.description.replace("|", "\\|")
        rows.append(f"| [{label}]({p.url}) | {p.tier} | {desc} |")
    note = ("Generated by `python3 site/tools/tiers.py` from the manifests; "
            "the reasons for each tier are on [the tiers page](https://volland.github.io/vertep/docs/tiers.html).")
    return "\n".join(rows) + "\n\n" + note


def page_table(packages):
    out = []
    for tier in TIERS:
        group = [p for p in by_tier(packages) if p.tier == tier]
        out.append(f'    <h3 id="{tier}">{tier.capitalize()} ({len(group)})</h3>')
        out.append("    <table>")
        out.append("      <thead><tr><th>Package</th><th>Where</th><th>Why this tier</th></tr></thead>")
        out.append("      <tbody>")
        for p in group:
            if p.published:
                where = f'<a href="{p.url}">{p.registry}</a>'
            elif p.ships_as:
                where = f"ships as {escape(p.ships_as)}"
            else:
                where = "not published"
            name = escape(p.name) if p.kind != "python" else "vertep (Python)"
            out.append(f"        <tr><td><code>{name}</code></td><td>{where}</td><td>{escape(p.reason or '', quote=False)}</td></tr>")
        out.append("      </tbody>")
        out.append("    </table>")
    return "\n".join(out)


def splice(text, body, path):
    pattern = re.compile(re.escape(BEGIN) + r".*?" + re.escape(END), re.S)
    if not pattern.search(text):
        raise SystemExit(f"{path.relative_to(ROOT)}: no {BEGIN} ... {END} markers")
    return pattern.sub(lambda _: f"{BEGIN}\n{body}\n{END}", text, count=1)


# @tg: implements:: [[openspec:production-readiness#Stability Tiers]]
def main(argv):
    check = "--check" in argv
    packages, problems = collect()
    if problems:
        print("\n".join(problems), file=sys.stderr)
        sys.exit(1)
    stale = []
    for path, body in ((README, readme_table(packages)), (PAGE, page_table(packages))):
        old = path.read_text()
        new = splice(old, body, path)
        if new != old:
            if check:
                stale.append(str(path.relative_to(ROOT)))
            else:
                path.write_text(new)
                print(f"wrote {path.relative_to(ROOT)}")
    if stale:
        print("stale tier tables in " + ", ".join(stale)
              + ": run python3 site/tools/tiers.py and commit the result", file=sys.stderr)
        sys.exit(1)
    counts = ", ".join(f"{sum(p.tier == t for p in packages)} {t}" for t in TIERS)
    print(f"{len(packages)} packages: {counts}" + ("; tables are current" if check else ""))


def self_test():
    """Run both failure cases of the check on a scratch copy of the manifests and tables."""
    import shutil
    import tempfile

    global ROOT, README, PAGE
    real = ROOT
    files = ["Cargo.toml", "README.md", "site/docs/tiers.html", "bindings/python/pyproject.toml"]
    files += [str(p.relative_to(real)) for p in real.glob("crates/*/Cargo.toml")]
    files += [str(p.relative_to(real)) for p in real.glob("bindings/js/packages/*/package.json")]
    with tempfile.TemporaryDirectory() as tmp:
        for f in files:
            (Path(tmp) / f).parent.mkdir(parents=True, exist_ok=True)
            shutil.copy(real / f, Path(tmp) / f)
        ROOT, README, PAGE = Path(tmp), Path(tmp) / "README.md", Path(tmp) / "site/docs/tiers.html"
        manifest = Path(tmp) / "crates/vertep-core/Cargo.toml"
        original = manifest.read_text()

        # @tg: verifies:: [[openspec:production-readiness#Stability Tiers#A tier is declared]] {level: integration}
        manifest.write_text(re.sub(r'(?m)^tier = .*\n', "", original, count=1))
        _, problems = collect()
        assert any("vertep-core declares no tier" in p for p in problems), problems

        # @tg: verifies:: [[openspec:production-readiness#Stability Tiers#A table cannot drift]] {level: integration}
        manifest.write_text(re.sub(r'(?m)^tier = .*$', 'tier = "experimental"', original, count=1))
        try:
            main(["--check"])
        except SystemExit as e:
            assert e.code == 1, e.code
        else:
            raise AssertionError("a changed tier with a stale table passed the check")
    ROOT, README, PAGE = real, real / "README.md", real / "site" / "docs" / "tiers.html"
    print("self-test: a missing tier is named and a stale table fails the check")


if __name__ == "__main__":
    if "--self-test" in sys.argv[1:]:
        self_test()
    else:
        main(sys.argv[1:])
